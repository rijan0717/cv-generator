/**
 * The designed templates.
 *
 * Each entry is data, not markup: `DesignedTemplate` renders any of them,
 * and `engine.css` styles every choice. Adding a template here is adding an
 * object — which is the whole point of the engine, and why fifty templates
 * is a realistic target where fifty hand-written components was not.
 *
 * Every design also carries `defaults`: the palette and font pairing
 * applied when a user picks it. A template is not only a layout — Scholar
 * is maroon on EB Garamond and Orbit is indigo on Raleway, and swapping
 * those would make both unrecognisable. The user can still change any of
 * it afterwards in the Design tab.
 *
 * Fonts must be names from FONT_STACKS in templateUtils.js, because those
 * are the families index.html actually loads; anything else would render
 * in the preview and fall back to a system font in the PDF.
 */

